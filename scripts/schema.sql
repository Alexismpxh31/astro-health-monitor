-- AstroSalud · Supabase / PostgreSQL schema.
-- Hand-maintained. Do NOT run this file directly: scripts/gen-seed-sql.mjs combines it with
-- the seed generated from src/data/seed/*.json into supabase/setup_final.sql (the only script to run).
-- Mirrors the Dexie schema in src/db/db.js (the client adds syncStatus; the server does not need it).
--
-- Name mapping client -> server (to do in the sync layer, src/sync/):
--   reading.indicatorCode -> readings.indicator_id  (lookup indicators.code; ids match the client seed)
--   camelCase fields      -> snake_case columns     (alert.alertLevelId -> alerts.alert_level_id, ...)
--   recommendation.textEs / textEn -> recommendations.text {"es": ..., "en": ...}

-- =====================================================================
-- 1. Catalogs (seeded with the same fixed UUIDs as src/data/seed/catalogs.json; `code` is the stable key)
-- =====================================================================
create table roles (
  id   uuid primary key default gen_random_uuid(),
  code varchar(30) not null unique,           -- astronaut | flight_surgeon
  name varchar(50) not null
);

create table body_systems (
  id      uuid primary key default gen_random_uuid(),
  code    varchar(30) not null unique,        -- cardiovascular | musculoskeletal | immune | behavioral | radiation
  name_es varchar(60) not null,
  name_en varchar(60) not null
);

create table units (
  id     uuid primary key default gen_random_uuid(),
  symbol varchar(10) not null unique,
  name   varchar(60) not null
);

create table indicators (
  id             uuid primary key default gen_random_uuid(),
  code           varchar(20) not null unique,  -- HR, SPO2, SBP, ...
  name_es        varchar(100) not null,
  name_en        varchar(100) not null,
  body_system_id uuid not null references body_systems(id) on delete restrict,
  unit_id        uuid not null references units(id) on delete restrict,
  is_live        boolean not null default false  -- true = streamed by a sensor, false = lab / daily value
);

create table alert_levels (
  id       uuid primary key default gen_random_uuid(),
  code     varchar(20) not null unique,        -- normal | caution | critical
  name_es  varchar(30) not null,
  name_en  varchar(30) not null,
  color    varchar(7)  not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  severity smallint    not null unique
);

create table symptoms (
  id      uuid primary key default gen_random_uuid(),
  code    varchar(30) not null unique,
  name_es varchar(100) not null,
  name_en varchar(100) not null
);

create table sensor_types (
  id   uuid primary key default gen_random_uuid(),
  code varchar(30) not null unique,
  name varchar(60) not null
);

-- =====================================================================
-- 2. Mission
-- =====================================================================
create table missions (
  id          uuid primary key default gen_random_uuid(),
  name        varchar(100) not null,
  destination varchar(100),
  start_date  timestamptz,
  end_date    timestamptz,
  check (end_date is null or start_date is null or end_date >= start_date)
);

create table users (
  id           uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete set null,  -- link to Supabase Auth (JWT)
  first_name   varchar(100) not null,
  last_name    varchar(100) not null,
  role_id      uuid not null references roles(id) on delete restrict,
  pin_salt     varchar(64)  not null,                 -- offline login: sha256(pin_salt || pin) = pin_hash
  pin_hash     varchar(64)  not null,                 -- hex SHA-256 (Web Crypto)
  active       boolean not null default true
);

create table crew (
  mission_id         uuid not null references missions(id) on delete restrict,
  user_id            uuid not null references users(id) on delete restrict,
  is_medical_officer boolean not null default false,
  primary key (mission_id, user_id)
);

-- =====================================================================
-- 3. Operation
-- =====================================================================
create table sensors (
  id             uuid primary key default gen_random_uuid(),
  sensor_type_id uuid not null references sensor_types(id) on delete restrict,
  model          varchar(100),
  user_id        uuid not null references users(id) on delete restrict
);

create table readings (
  id           uuid primary key,                        -- generated by the client (crypto.randomUUID())
  user_id      uuid not null references users(id) on delete restrict,
  indicator_id uuid not null references indicators(id) on delete restrict,
  sensor_id    uuid references sensors(id) on delete restrict,
  value        numeric not null check (value <> 'NaN'::numeric),
  measured_at  timestamptz not null,
  source       varchar(10) not null default 'simulated' check (source in ('simulated', 'dataset', 'ble')),
  synced_at    timestamptz not null default now()       -- time the server received it
);
create index readings_user_indicator_time_idx on readings (user_id, indicator_id, measured_at desc);
create index readings_measured_at_idx on readings (measured_at desc);

create table thresholds (
  id            text primary key,                       -- stable seed id ('TH_HR') or a client UUID as text
  indicator_id  uuid not null references indicators(id) on delete restrict,
  user_id       uuid references users(id) on delete restrict,   -- NULL = general threshold
  min_critical  numeric not null,
  min_normal    numeric not null,
  max_normal    numeric not null,
  max_critical  numeric not null,
  updated_by    uuid references users(id) on delete restrict,
  valid_from    timestamptz not null default now(),
  source        text,                                   -- where the reference value comes from
  validated     boolean not null default false,         -- false = estimated, TODO: validar fuente
  updated_at    timestamptz not null default now(),     -- for "pull changes since X" (Earth wins)
  constraint chk_thresholds_order check (
    min_critical <= min_normal and min_normal <= max_normal and max_normal <= max_critical
  )
);
create unique index thresholds_general_uq  on thresholds (indicator_id, valid_from) where user_id is null;
create unique index thresholds_personal_uq on thresholds (indicator_id, user_id, valid_from) where user_id is not null;

create table recommendations (
  id             text primary key,                      -- stable seed id ('REC_HR_LOW_CAUTION')
  indicator_id   uuid not null references indicators(id) on delete restrict,
  alert_level_id uuid not null references alert_levels(id) on delete restrict,
  direction      varchar(4) check (direction in ('low', 'high')),   -- NULL = applies to both
  text           jsonb not null check (text ? 'es' and text ? 'en')  -- {"es": "...", "en": "..."}; %value% / %unit% placeholders
);
create unique index recommendations_uq on recommendations (indicator_id, alert_level_id, coalesce(direction, ''));

create table alerts (
  id                uuid primary key,                   -- generated by the client
  reading_id        uuid not null references readings(id) on delete restrict,
  recommendation_id text references recommendations(id) on delete restrict,  -- null if no recommendation matched
  alert_level_id    uuid not null references alert_levels(id) on delete restrict,  -- caution | critical
  direction         varchar(4) check (direction in ('low', 'high')),             -- side of the normal range
  generated_at      timestamptz not null,
  attended_at       timestamptz
  -- no user_id: derived from readings. Level and direction are stored because
  -- recommendation_id can be null (no recommendation matched).
);
create index alerts_reading_idx on alerts (reading_id);
create index alerts_pending_idx on alerts (generated_at desc) where attended_at is null;

create table daily_checkins (
  id          uuid primary key,
  user_id     uuid not null references users(id) on delete restrict,
  date        date not null,
  mood        smallint not null check (mood between 1 and 5),
  sleep_hours numeric(4,1) not null check (sleep_hours between 0 and 24),
  stress      smallint not null check (stress between 1 and 5),
  notes       text,
  unique (user_id, date)
);

create table checkin_symptoms (
  checkin_id uuid not null references daily_checkins(id) on delete restrict,
  symptom_id uuid not null references symptoms(id) on delete restrict,
  primary key (checkin_id, symptom_id)
);

create table messages (
  id           uuid primary key,
  sender_id    uuid not null references users(id) on delete restrict,
  recipient_id uuid not null references users(id) on delete restrict,
  content      text not null check (length(content) > 0),
  sent_at      timestamptz not null default now(),
  read_at      timestamptz,
  updated_at   timestamptz not null default now(),
  check (sender_id <> recipient_id)
);
create index messages_recipient_idx on messages (recipient_id, sent_at desc);

-- updated_at triggers (server-wins tables: client pulls rows with updated_at > lastSync)
create function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create trigger thresholds_updated_at before update on thresholds for each row execute function public.set_updated_at();
create trigger messages_updated_at   before update on messages   for each row execute function public.set_updated_at();

-- =====================================================================
-- 4. Row Level Security (Supabase exposes tables over REST: without RLS anyone with the anon key can read everything)
-- =====================================================================

-- Helpers are SECURITY DEFINER so policies can look at users/crew without recursing into their own RLS.
create function public.app_user_id() returns uuid
language sql stable security definer set search_path = public as
$$ select id from public.users where auth_user_id = auth.uid() and active $$;

create function public.is_flight_surgeon() returns boolean
language sql stable security definer set search_path = public as
$$ select coalesce((select r.code = 'flight_surgeon' from public.users u join public.roles r on r.id = u.role_id
                    where u.auth_user_id = auth.uid() and u.active), false) $$;

create function public.shares_mission(target uuid) returns boolean
language sql stable security definer set search_path = public as
$$ select exists (select 1 from public.crew me join public.crew o on o.mission_id = me.mission_id
                  where me.user_id = public.app_user_id() and o.user_id = target) $$;

-- Own data, flight surgeon (whole crew) or crew medical officer (crewmates on the same mission).
-- TODO: the doc says "en emergencia"; for now the officer can read crewmates' data at all times.
create function public.can_view_user(target uuid) returns boolean
language sql stable security definer set search_path = public as
$$ select target = public.app_user_id()
       or public.is_flight_surgeon()
       or exists (select 1 from public.crew me join public.crew o on o.mission_id = me.mission_id
                  where me.user_id = public.app_user_id() and me.is_medical_officer and o.user_id = target) $$;

revoke all on all tables in schema public from anon;
grant usage on schema public to authenticated;

-- Catalogs and missions: read-only for logged-in users (they are changed with the service role / SQL editor)
do $$
declare t text;
begin
  foreach t in array array['roles','body_systems','units','indicators','alert_levels','symptoms','sensor_types','missions','recommendations']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('create policy %I on public.%I for select to authenticated using (true)', t || '_read', t);
  end loop;
end $$;

-- users / crew
alter table users enable row level security;
alter table crew  enable row level security;
grant select on users, crew to authenticated;
create policy users_read on users for select to authenticated
  using (id = public.app_user_id() or public.is_flight_surgeon() or public.shares_mission(id));
create policy crew_read on crew for select to authenticated
  using (user_id = public.app_user_id() or public.is_flight_surgeon() or public.shares_mission(user_id));

-- sensors
alter table sensors enable row level security;
grant select, insert, update on sensors to authenticated;
create policy sensors_read   on sensors for select to authenticated using (public.can_view_user(user_id));
create policy sensors_insert on sensors for insert to authenticated with check (user_id = public.app_user_id());
create policy sensors_update on sensors for update to authenticated using (user_id = public.app_user_id()) with check (user_id = public.app_user_id());

-- readings: append-only (no update, no delete)
alter table readings enable row level security;
grant select, insert on readings to authenticated;
create policy readings_read   on readings for select to authenticated using (public.can_view_user(user_id));
create policy readings_insert on readings for insert to authenticated with check (user_id = public.app_user_id());

-- alerts: owner of the reading creates them and marks them attended
alter table alerts enable row level security;
grant select, insert, update on alerts to authenticated;
create policy alerts_read on alerts for select to authenticated
  using (exists (select 1 from readings r where r.id = reading_id and public.can_view_user(r.user_id)));
create policy alerts_insert on alerts for insert to authenticated
  with check (exists (select 1 from readings r where r.id = reading_id and r.user_id = public.app_user_id()));
create policy alerts_update on alerts for update to authenticated
  using (exists (select 1 from readings r where r.id = reading_id and r.user_id = public.app_user_id()))
  with check (exists (select 1 from readings r where r.id = reading_id and r.user_id = public.app_user_id()));

-- daily check-ins
alter table daily_checkins enable row level security;
grant select, insert, update on daily_checkins to authenticated;
create policy checkins_read   on daily_checkins for select to authenticated using (public.can_view_user(user_id));
create policy checkins_insert on daily_checkins for insert to authenticated with check (user_id = public.app_user_id());
create policy checkins_update on daily_checkins for update to authenticated using (user_id = public.app_user_id()) with check (user_id = public.app_user_id());

alter table checkin_symptoms enable row level security;
grant select, insert on checkin_symptoms to authenticated;
create policy checkin_symptoms_read on checkin_symptoms for select to authenticated
  using (exists (select 1 from daily_checkins c where c.id = checkin_id and public.can_view_user(c.user_id)));
create policy checkin_symptoms_insert on checkin_symptoms for insert to authenticated
  with check (exists (select 1 from daily_checkins c where c.id = checkin_id and c.user_id = public.app_user_id()));

-- thresholds: everyone reads the general ones and their own; only the flight surgeon writes
alter table thresholds enable row level security;
grant select, insert, update on thresholds to authenticated;
create policy thresholds_read on thresholds for select to authenticated
  using (user_id is null or public.can_view_user(user_id));
create policy thresholds_insert on thresholds for insert to authenticated
  with check (public.is_flight_surgeon() and updated_by = public.app_user_id());
create policy thresholds_update on thresholds for update to authenticated
  using (public.is_flight_surgeon()) with check (public.is_flight_surgeon() and updated_by = public.app_user_id());

-- messages: sender and recipient only
alter table messages enable row level security;
grant select, insert, update on messages to authenticated;
create policy messages_read   on messages for select to authenticated using (sender_id = public.app_user_id() or recipient_id = public.app_user_id());
create policy messages_insert on messages for insert to authenticated with check (sender_id = public.app_user_id());
create policy messages_update on messages for update to authenticated using (recipient_id = public.app_user_id()) with check (recipient_id = public.app_user_id());
