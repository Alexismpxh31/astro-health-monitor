// Generates supabase/setup_final.sql = header + drops + scripts/schema.sql + seed.
// The seed is built from src/data/seed/*.json (the single source of truth), so the
// Supabase data always matches what the client loads into IndexedDB.
//
// Usage: npm run gen:sql            (or: node scripts/gen-seed-sql.mjs)
//        npm run gen:sql -- --help  (prints the usage, writes nothing)

import fs from 'node:fs'

const USAGE = `Usage: node scripts/gen-seed-sql.mjs [options]

Generates supabase/setup_final.sql (header + drops + scripts/schema.sql + seed).
The seed is built from src/data/seed/*.json, the same files the client loads.

Options:
  -h, --help   Show this help and exit without generating or writing any file.

Without options it overwrites supabase/setup_final.sql.
`

// Handled before anything is read, generated or written.
const args = process.argv.slice(2)
if (args.includes('--help') || args.includes('-h')) {
  process.stdout.write(USAGE)
  process.exit(0)
}
if (args.length > 0) {
  process.stderr.write(`Unknown option: ${args[0]}

${USAGE}`)
  process.exit(1)
}

const root = new URL('../', import.meta.url)
const read = (path) => fs.readFileSync(new URL(path, root), 'utf8').replaceAll('\r', '')
const readJson = (path) => JSON.parse(read(path))

const catalogs = readJson('src/data/seed/catalogs.json')
const thresholds = readJson('src/data/seed/thresholds.json')
const recommendations = readJson('src/data/seed/recommendations.json')
const { users, crew } = readJson('src/data/seed/users.json')

// ---------- SQL helpers ----------

/** SQL literal for a JS value. */
function lit(value) {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  return `'${String(value).replaceAll("'", "''")}'`
}

const tuples = (rows) => rows.map((row) => `  (${row.map(lit).join(', ')})`).join(',\n')

function byId(rows, id, what) {
  const row = rows.find((candidate) => candidate.id === id)
  if (!row) throw new Error(`Seed error: ${what} ${id} not found`)
  return row
}
const indicatorCode = (id) => byId(catalogs.indicators, id, 'indicator').code
const levelCode = (id) => byId(catalogs.alertLevels, id, 'alert level').code
// thresholds.mode: rows without it are absolute limits; 'baseline' = deviations from the personal baseline.
const THRESHOLD_MODES = ['absolute', 'baseline']
const DEFAULT_THRESHOLD_MODE = 'absolute'
const thresholdMode = (row) => row.mode ?? DEFAULT_THRESHOLD_MODE

const roleCode = (id) => byId(catalogs.roles, id, 'role').code

// ---------- Consistency checks (fail the generation instead of producing a broken script) ----------

for (const row of thresholds) {
  const ordered =
    row.minCritical <= row.minNormal &&
    row.minNormal <= row.maxNormal &&
    row.maxNormal <= row.maxCritical
  if (!ordered) throw new Error(`Seed error: threshold ${row.id} breaks min_critical <= min_normal <= max_normal <= max_critical`)
  if (!THRESHOLD_MODES.includes(thresholdMode(row))) throw new Error(`Seed error: threshold ${row.id} has an invalid mode (use ${THRESHOLD_MODES.join(' | ')})`)
}
for (const row of recommendations) {
  if (!row.textEs || !row.textEn) throw new Error(`Seed error: recommendation ${row.id} needs textEs and textEn`)
  if (![null, 'low', 'high'].includes(row.direction)) throw new Error(`Seed error: recommendation ${row.id} has an invalid direction`)
}

// ---------- Seed ----------

const seed = `-- =====================================================================
-- 5. Seed. GENERATED by scripts/gen-seed-sql.mjs from src/data/seed/*.json.
--    Do not edit by hand: edit the JSON and run \`npm run gen:sql\`.
--    Catalog ids are the same fixed UUIDs the client uses, so client rows sync as-is.
-- =====================================================================

insert into roles (id, code, name) values
${tuples(catalogs.roles.map((r) => [r.id, r.code, r.nameEn]))}
on conflict (code) do update set name = excluded.name;

insert into body_systems (id, code, name_es, name_en) values
${tuples(catalogs.bodySystems.map((r) => [r.id, r.code, r.nameEs, r.nameEn]))}
on conflict (code) do update set name_es = excluded.name_es, name_en = excluded.name_en;

insert into units (id, symbol, name) values
${tuples(catalogs.units.map((r) => [r.id, r.symbol, r.nameEs]))}
on conflict (symbol) do update set name = excluded.name;

insert into alert_levels (id, code, name_es, name_en, color, severity) values
${tuples(catalogs.alertLevels.map((r) => [r.id, r.code, r.nameEs, r.nameEn, r.color, r.severity]))}
on conflict (code) do update set name_es = excluded.name_es, name_en = excluded.name_en, color = excluded.color, severity = excluded.severity;

insert into symptoms (id, code, name_es, name_en) values
${tuples(catalogs.symptoms.map((r) => [r.id, r.code, r.nameEs, r.nameEn]))}
on conflict (code) do update set name_es = excluded.name_es, name_en = excluded.name_en;

insert into sensor_types (id, code, name) values
${tuples(catalogs.sensorTypes.map((r) => [r.id, r.code, r.nameEs]))}
on conflict (code) do update set name = excluded.name;

insert into indicators (id, code, name_es, name_en, body_system_id, unit_id, is_live) values
${tuples(catalogs.indicators.map((r) => [r.id, r.code, r.nameEs, r.nameEn, r.bodySystemId, r.unitId, r.isLive]))}
on conflict (code) do update set name_es = excluded.name_es, name_en = excluded.name_en,
  body_system_id = excluded.body_system_id, unit_id = excluded.unit_id, is_live = excluded.is_live;

-- General thresholds (user_id null).
insert into thresholds (id, indicator_id, user_id, min_critical, min_normal, max_normal, max_critical, valid_from, source, validated, mode)
select v.id, i.id, null, v.min_c, v.min_n, v.max_n, v.max_c, v.valid_from::timestamptz, v.source, v.validated, v.mode
from (values
${tuples(thresholds.map((r) => [r.id, indicatorCode(r.indicatorId), r.minCritical, r.minNormal, r.maxNormal, r.maxCritical, r.validFrom, r.source, r.validated, thresholdMode(r)]))}
) as v(id, code, min_c, min_n, max_n, max_c, valid_from, source, validated, mode)
join indicators i on i.code = v.code
on conflict (id) do update set min_critical = excluded.min_critical, min_normal = excluded.min_normal,
  max_normal = excluded.max_normal, max_critical = excluded.max_critical, source = excluded.source, validated = excluded.validated, mode = excluded.mode;

insert into recommendations (id, indicator_id, alert_level_id, direction, text)
select v.id, i.id, l.id, v.direction, v.text::jsonb
from (values
${tuples(recommendations.map((r) => [r.id, indicatorCode(r.indicatorId), levelCode(r.alertLevelId), r.direction, JSON.stringify({ es: r.textEs, en: r.textEn })]))}
) as v(id, code, level_code, direction, text)
join indicators i on i.code = v.code
join alert_levels l on l.code = v.level_code
on conflict (id) do update set indicator_id = excluded.indicator_id, alert_level_id = excluded.alert_level_id,
  direction = excluded.direction, text = excluded.text;

-- Demo mission and crew (fake people, demo PINs: surgeon 9999, astronauts 1111 / 2222 / 3333)
insert into missions (id, name, destination, start_date, end_date) values
${tuples(catalogs.missions.map((r) => [r.id, r.name, r.destination, r.startDate, r.endDate]))}
on conflict (id) do nothing;

insert into users (id, first_name, last_name, role_id, pin_salt, pin_hash)
select v.id::uuid, v.first_name, v.last_name, r.id, v.pin_salt, v.pin_hash
from (values
${tuples(users.map((r) => [r.id, r.firstName, r.lastName, roleCode(r.roleId), r.pinSalt, r.pinHash]))}
) as v(id, first_name, last_name, role_code, pin_salt, pin_hash)
join roles r on r.code = v.role_code
on conflict (id) do nothing;

insert into crew (mission_id, user_id, is_medical_officer) values
${tuples(crew.map((r) => [r.missionId, r.userId, r.isMedicalOfficer]))}
on conflict do nothing;

-- To let a demo user call the API, create them in Supabase Auth (Dashboard > Authentication > Users) and link:
--   update users set auth_user_id = '<auth uuid>' where id = '${users.find((u) => roleCode(u.roleId) === 'astronaut').id}';
`

// ---------- Header, drops, verification ----------

const codes = catalogs.indicators.map((r) => r.code)
const wrap = (items, width) => {
  const lines = ['']
  for (const item of items) {
    if ((lines.at(-1) + item).length > width) lines.push('')
    lines[lines.length - 1] += (lines.at(-1) ? ', ' : '') + item
  }
  return lines
}

const header = `-- =====================================================================
-- AstroSalud · SINGLE SUPABASE SCRIPT (schema + seed)   ->  supabase/setup_final.sql
-- Paste ALL of it in Supabase > SQL Editor and run. Safe to run more than once.
--
-- !! WARNING: this script DROPS and recreates every app table. All readings, alerts,
-- !! check-ins, messages, personal thresholds and demo users are DELETED.
-- !! It does not touch auth.users or anything outside these tables.
-- !! If the RLS notice appears, choose "Run and enable RLS".
--
-- GENERATED by scripts/gen-seed-sql.mjs (schema: scripts/schema.sql, data: src/data/seed/*.json).
-- Do not edit by hand: change the sources and run \`npm run gen:sql\`.
-- It replaces TODO_EN_UNO.sql and setup.sql (both obsolete).
--
-- CHANGES vs TODO_EN_UNO.sql
--  * One source of truth: the seed is generated from the same JSON files the client loads.
--  * Catalog rows use the same fixed UUIDs as the client (roles, body_systems, units,
--    indicators, alert_levels, symptoms, sensor_types), so client rows sync without id lookups.
--  * alerts: new columns alert_level_id and direction ('low' | 'high').
--  * thresholds: new column mode ('absolute' | 'baseline', default 'absolute'). 'baseline' rows hold
--    deviations from the personal baseline instead of absolute limits (src/rules/baseline.js).
--  * TH_RAD_DOSE: 0 / 0 / 400 / 600 mSv (NASA-STD-3001 career limit), validated.
--  * TH_BMD: -1.5 / -1.0 / 0.5 / 2 % per month (NASA HRP bone loss rate), validated.
--  * Other thresholds that cited the "NASA HRP compendium": same values, source relabelled
--    as a general clinical reference (demo values), validated = false.
--  * Recommendations reworded to drop claims not backed by the challenge sources:
--    REC_PVT_HIGH_CAUTION, REC_SLEEP_H_LOW_CAUTION, REC_BMD_LOW_CAUTION, REC_BMD_LOW_CRITICAL,
--    REC_MUSCLE_LOW_CAUTION, REC_RAD_D_HIGH_CAUTION, REC_RAD_D_HIGH_CRITICAL, REC_RAD_DOSE_HIGH_CRITICAL.
--  * Catalog: RAD_D is_live = true, RAD_DOSE is_live = false, TSKIN belongs to 'immune'.
--
-- OFFICIAL INDICATOR CODES (${codes.length})
${wrap(codes, 70).map((line) => `--   ${line}`).join(',\n')}
-- Alert levels: ${catalogs.alertLevels.map((r) => r.code).join(' | ')}
-- =====================================================================
`

const drops = `drop table if exists checkin_symptoms, daily_checkins, alerts, readings, messages, recommendations,
  thresholds, sensors, crew, users, missions, indicators, symptoms, sensor_types, alert_levels, units,
  body_systems, roles cascade;
drop function if exists public.set_updated_at(), public.app_user_id(), public.is_flight_surgeon(),
  public.shares_mission(uuid), public.can_view_user(uuid) cascade;
`

const expected = {
  indicators: catalogs.indicators.length,
  thresholds: thresholds.length,
  recommendations: recommendations.length,
  users: users.length,
}
const verification = `-- =====================================================================
-- 6. Verification. Expected: ${Object.entries(expected).map(([name, count]) => `${name} = ${count}`).join(', ')}
-- =====================================================================
select
${Object.keys(expected).map((name) => `  (select count(*) from ${name}) as ${name}`).join(',\n')};
`

const output = [header, drops, read('scripts/schema.sql'), seed, verification].join('\n')
fs.writeFileSync(new URL('supabase/setup_final.sql', root), output)
console.log(`supabase/setup_final.sql written: ${Object.entries(expected).map(([name, count]) => `${count} ${name}`).join(', ')}`)
